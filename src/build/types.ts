// Fresh writes a small TypeScript file alongside every route, middleware,
// layout, and error page you author — tucked away under `.fresh/types/`. You
// never edit these; they exist so your source files can import helpers that
// already know the right `Params`, `State`, and `Data` types for that exact
// spot in the tree.
//
// What makes them feel "next to" your code is TypeScript's `rootDirs`. With it,
// the generated
//
//     .fresh/types/routes/admin/post/$[slug].ts
//
// virtually sits beside
//
//     routes/admin/post/[slug].tsx
//
// so the route can write `import { handler, page, type Params } from
// "./$[slug].ts"` and get its param names lifted straight out of its own
// filename.
//
// The typing helpers those files import (`Handler`, `MiddlewareContext`, and
// friends) ship from the `fresh` package and are referenced by bare specifier —
// ordinary node_modules resolution finds them as soon as the project depends on
// `fresh`.
//
// Everything here is a pure string builder: each `*TypeFileContent` returns the
// text of one generated file, and the matching `generate*` wrapper pairs that
// text with the path it belongs at. Staying pure keeps them easy to unit-test —
// feed in a path, assert on the emitted source.

/** The banner every generated typings file opens with. */
const AUTOGEN_HEADER = `// Auto-generated by Fresh — do not edit.`;

export interface GeneratedTypeFile {
  /** Project-relative output path, e.g. `.fresh/types/routes/blog/$[slug].ts`. */
  path: string;
  content: string;
}

/**
 * Map a route source path to its sibling typings path: keep the folders, drop
 * the extension, and prefix the filename with `$` so the generated file sorts
 * and reads as a companion to the original
 * (`routes/blog/[slug].tsx` → `.fresh/types/routes/blog/$[slug].ts`).
 */
export function typeFilePath(relativeRoutePath: string): string {
  const segments = relativeRoutePath.split("/").filter(Boolean);
  if (segments.length === 0) {
    throw new TypeError(`typeFilePath: empty path (got ${JSON.stringify(relativeRoutePath)})`);
  }
  const last = segments.pop()!;
  const base = last.replace(/\.(tsx|ts|jsx|js)$/, "");
  segments.push(`$${base}.ts`);
  return ".fresh/types/" + segments.join("/");
}

/**
 * Render the body of a `Params` interface from a route's dynamic-segment names.
 * No params yields an empty `{}`; `["slug"]` yields `{ slug: string }` — one
 * `string` field per segment. Every Fresh route param is a string, so there's
 * nothing fancier to express.
 */
function paramsInterfaceBody(params: readonly string[]): string {
  if (params.length === 0) return "{}";
  return `{\n${params.map((p) => `  ${p}: string;`).join("\n")}\n}`;
}

/**
 * Bring a `State` type into a generated file under the name `local`. When a
 * route or middleware has an upstream `_middleware`, we import that
 * middleware's exported `State` (aliasing it to `local` when the names differ).
 * When there's nothing above it, we fall back to a fresh *empty interface*
 * rather than `Record<string, never>` — that way the consumer can still augment
 * `ctx.state` downstream without TypeScript rejecting the added properties.
 */
function stateBinding(fromTypeFile: string, source: string | null, local: string): string {
  if (!source) return `interface ${local} {}`;
  const spec = relativeImport(fromTypeFile, typeFilePath(source));
  const clause = local === "State" ? "State" : `State as ${local}`;
  return `import type { ${clause} } from ${JSON.stringify(spec)};`;
}

/**
 * The `Data` type line for a route. When the route exports `handlers`, the data
 * shape is inferred from their return types via `InferData`; when it doesn't,
 * `Data` is `never` — matching the framework's auto-`GET` fallback, which
 * renders the page with no handler data.
 */
function dataBinding(routePath: string, userExportsHandlers: boolean): string {
  if (!userExportsHandlers) return `type Data = never;`;
  const importSpec = JSON.stringify(`./${routePath.split("/").pop()!}`);
  return `type Data = InferData<typeof import(${importSpec}).handlers>;`;
}

/**
 * The typings file for a route — exports a typed `handler` and `page` helper,
 * each pre-wired with this route's `Params`, `State`, and `Data`.
 *
 * - `params` — the route's dynamic-segment names (see {@link paramsFromFilePath}).
 * - `closestMiddleware` — project-relative path to the nearest `_middleware`
 *   source, or `null` when there is none; this is what drives `ctx.state`.
 * - `userExportsHandlers` — whether the route source has `export const
 *   handlers = …`, which decides how `Data` is derived (see {@link dataBinding}).
 */
export function typeFileContent(
  params: readonly string[],
  routePath: string,
  closestMiddleware: string | null,
  userExportsHandlers: boolean,
): string {
  return [
    AUTOGEN_HEADER,
    `import type { VNode } from "preact";`,
    `import type { Handler, InferData, PageProps } from "fresh/types";`,
    stateBinding(typeFilePath(routePath), closestMiddleware, "State"),
    dataBinding(routePath, userExportsHandlers),
    ``,
    `export interface Params ${paramsInterfaceBody(params)}`,
    ``,
    `export function handler<H extends Handler<Params, State>>(h: H): H {`,
    `  return h;`,
    `}`,
    ``,
    `// \`page\` is a sibling of \`handler\` (not wrapped in an object) so the`,
    `// page's typing can reference \`InferData<typeof import("./...").handlers>\``,
    `// without TS hitting a circular dependency between the type of a property`,
    `// and the value of \`handlers\` (which references the same object).`,
    `export function page(`,
    `  fn: (props: PageProps<Data, Params, State>) => VNode,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  ].join("\n");
}

/** Bundle a route's typings path with its rendered content. */
export function generateRouteTypeFile(
  relativeRoutePath: string,
  params: readonly string[],
  closestMiddleware: string | null,
  userExportsHandlers: boolean,
): GeneratedTypeFile {
  return {
    path: typeFilePath(relativeRoutePath),
    content: typeFileContent(params, relativeRoutePath, closestMiddleware, userExportsHandlers),
  };
}

/**
 * Does this route source export `handlers`? A quick regex beats spinning up a
 * TS parser, and it's all we need to decide whether to infer `Data` from the
 * handlers or fall back to `never`. Catches the `const`/`let`/`var`/`function`
 * export forms.
 */
export function detectHandlersExport(source: string): boolean {
  return /(^|\n)\s*export\s+(?:const|let|var|function)\s+handlers\b/.test(source);
}

/**
 * The `OwnState` line for a middleware. When the middleware source exports its
 * own `State` (`export interface State` / `export type State`), we read it back
 * with a dotted `import(...)` type — which works even for type-only exports.
 * Otherwise the middleware adds nothing of its own and `OwnState` is simply its
 * parent's state.
 */
function ownStateLine(middlewarePath: string, userExportsState: boolean): string {
  if (!userExportsState) return `type OwnState = ParentState;`;
  const importSpec = JSON.stringify(`./${middlewarePath.split("/").pop()!}`);
  return `type OwnState = import(${importSpec}).State;`;
}

/**
 * The typings file for a `_middleware` — exports a typed `middleware` helper.
 *
 * A middleware sees two states: `ParentState`, whatever the middleware above it
 * produced (or an empty interface at the root), and `OwnState`, what this one
 * adds on top (see {@link ownStateLine}). Its `Params` come from the folder
 * path the same way a route's do — every route this middleware runs for shares
 * those dynamic segments, so they're known statically.
 */
export function middlewareTypeFileContent(
  middlewarePath: string,
  parentMiddleware: string | null,
  userExportsState: boolean,
  params: readonly string[],
): string {
  return [
    AUTOGEN_HEADER,
    `import type { MiddlewareFn } from "fresh/types";`,
    stateBinding(typeFilePath(middlewarePath), parentMiddleware, "ParentState"),
    ownStateLine(middlewarePath, userExportsState),
    ``,
    `export type { ParentState };`,
    `export type State = OwnState;`,
    ``,
    `export interface Params ${paramsInterfaceBody(params)}`,
    ``,
    `export function middleware(`,
    `  fn: MiddlewareFn<ParentState, OwnState, Params>,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  ].join("\n");
}

/**
 * The typings file for `routes/_app.tsx` — exports an identity `app` helper
 * typed as `AppComponent`, so the wrapper gets `children` (and `req`) typing.
 * The generated route module pulls the user's default export via a wildcard
 * import, so all this file owes them is the helper.
 */
export function appTypeFileContent(): string {
  return [
    AUTOGEN_HEADER,
    `import type { AppComponent } from "fresh/types";`,
    ``,
    `export function app(fn: AppComponent): AppComponent {`,
    `  return fn;`,
    `}`,
    ``,
  ].join("\n");
}

/** Bundle the `_app` typings path with its rendered content. */
export function generateAppTypeFile(appPath: string): GeneratedTypeFile {
  return {
    path: typeFilePath(appPath),
    content: appTypeFileContent(),
  };
}

/**
 * The typings file for a `_layout` — exports an identity `layout` helper typed
 * as `LayoutComponent`. `State` comes from the closest `_middleware`, so a
 * layout can read whatever the upstream chain produced. `Params`, though, stays
 * a plain string record: a single layout wraps many sibling routes whose param
 * sets differ, so there's no one param shape to pin it to.
 */
export function layoutTypeFileContent(
  layoutPath: string,
  closestMiddleware: string | null,
): string {
  return [
    AUTOGEN_HEADER,
    `import type { LayoutComponent } from "fresh/types";`,
    stateBinding(typeFilePath(layoutPath), closestMiddleware, "State"),
    ``,
    `export function layout(`,
    `  fn: LayoutComponent<unknown, Record<string, string>, State>,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  ].join("\n");
}

/** Bundle a layout's typings path with its rendered content. */
export function generateLayoutTypeFile(
  layoutPath: string,
  closestMiddleware: string | null,
): GeneratedTypeFile {
  return {
    path: typeFilePath(layoutPath),
    content: layoutTypeFileContent(layoutPath, closestMiddleware),
  };
}

/**
 * The typings file for `routes/_error.tsx` — exports a typed `handler` (whose
 * context carries the thrown `error`) and a typed `page` (whose props carry it).
 *
 * The error route is reachable from anywhere, including a 404 that never ran a
 * middleware, so we can't know which `State` is live at dispatch time. We cover
 * every possibility by unioning each middleware's `State` together with
 * `EmptyState`. It carries no `Params` of its own — `_error.tsx` isn't
 * URL-addressable.
 */
export function errorTypeFileContent(errorPath: string, allMiddlewares: readonly string[]): string {
  const errorTypeFile = typeFilePath(errorPath);

  // One aliased import per middleware; `State` is their union plus `EmptyState`.
  const imports: string[] = [];
  const aliases = ["EmptyState"];
  allMiddlewares.forEach((mw, i) => {
    imports.push(stateBinding(errorTypeFile, mw, `State_${i}`));
    aliases.push(`State_${i}`);
  });

  return [
    AUTOGEN_HEADER,
    `import type { VNode } from "preact";`,
    `import type { EmptyState, ErrorHandler, ErrorPageProps, InferData } from "fresh/types";`,
    ...imports,
    ``,
    `type State = ${aliases.join(" | ")};`,
    `export interface Params {}`,
    dataBinding(errorPath, true),
    ``,
    `export function handler<H extends ErrorHandler<Params, State>>(h: H): H {`,
    `  return h;`,
    `}`,
    ``,
    `export function page(`,
    `  fn: (props: ErrorPageProps<Data, Params, State>) => VNode,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  ].join("\n");
}

/** Bundle the `_error` typings path with its rendered content. */
export function generateErrorTypeFile(
  errorPath: string,
  allMiddlewares: readonly string[],
): GeneratedTypeFile {
  return {
    path: typeFilePath(errorPath),
    content: errorTypeFileContent(errorPath, allMiddlewares),
  };
}

/** Bundle a middleware's typings path with its rendered content. */
export function generateMiddlewareTypeFile(
  middlewarePath: string,
  parentMiddleware: string | null,
  userExportsState: boolean,
  params: readonly string[],
): GeneratedTypeFile {
  return {
    path: typeFilePath(middlewarePath),
    content: middlewareTypeFileContent(middlewarePath, parentMiddleware, userExportsState, params),
  };
}

/**
 * Does this middleware source export its own `State` (`export interface State`
 * / `export type State`)? Like {@link detectHandlersExport}, a regex is enough
 * here — middleware files are small and this only decides whether `OwnState`
 * reads back the user's type or inherits the parent's.
 */
export function detectStateExport(source: string): boolean {
  return /(^|\n)\s*export\s+(?:interface|type)\s+State\b/.test(source);
}

/**
 * Pull the dynamic-segment names out of a route file path. Handles both the
 * plain `[name]` form and the `[...name]` catch-all (the leading dots are
 * dropped, so both surface as `name`).
 */
export function paramsFromFilePath(filePath: string): string[] {
  const out: string[] = [];
  const re = /\[(?:\.{3})?([^\]]+)\]/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(filePath)) !== null) {
    out.push(m[1]);
  }
  return out;
}

/**
 * A POSIX-style relative import specifier from one typings file to another —
 * the glue that lets a route's generated file point at its middleware's. Walks
 * past the shared parent folders, climbs out with `..` for the rest, and drops
 * the trailing `.ts` so it resolves under TypeScript's standard resolution.
 */
function relativeImport(fromPath: string, toPath: string): string {
  const fromDir = fromPath.split("/").slice(0, -1);
  const toParts = toPath.split("/");
  // Walk common prefix.
  let i = 0;
  while (i < fromDir.length && i < toParts.length - 1 && fromDir[i] === toParts[i]) {
    i++;
  }
  const ups = fromDir.length - i;
  const segs = toParts.slice(i);
  const rel = (ups === 0 ? ["."] : Array(ups).fill("..")).concat(segs).join("/");
  // Strip the `.ts` so the import works under TS's standard module resolution.
  return rel.replace(/\.ts$/, "");
}
