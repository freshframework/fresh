// Generates the per-route + per-middleware typings files under `.fresh/types/`.
//
// TypeScript users wire this in via `rootDirs` so that, e.g.,
//   .fresh/types/routes/admin/post/$[slug].ts
// virtually sits next to
//   routes/admin/post/[slug].tsx
// and the route file can `import { define, type Params } from "./$[slug].ts"`.
//
// The typing helpers (`Handler`, `MiddlewareContext`, etc.) live in the
// `fresh` package and are imported by package specifier — node_modules
// resolution finds them once the example workspace depends on `fresh`.

export interface GeneratedTypeFile {
  /** Project-relative output path, e.g. `.fresh/types/routes/blog/$[slug].ts`. */
  path: string;
  content: string;
}

/** Map a route source path to its sibling typings path. */
export function typeFilePath(relativeRoutePath: string): string {
  const segments = relativeRoutePath.split("/").filter(Boolean);
  if (segments.length === 0) {
    throw new TypeError(`typeFilePath: empty path (got ${JSON.stringify(relativeRoutePath)})`);
  }
  const last = segments.pop()!;
  const base = last.replace(/\.(tsx|ts|jsx|js)$/, "");
  segments.push(`$${base}.ts`);
  return ".fresh/types/" + segments.join("/");
}

/**
 * Render the handler typings file body for a route with the given param names.
 *
 * - `closestMiddleware` — project-relative path to the nearest `_middleware`
 *   source, or `null` when there is none. Drives `ctx.state` typing.
 * - `userExportsHandlers` — when `true`, the user's route source has an
 *   `export const handlers = …`; the generated `Data` type is inferred from
 *   it via `InferData<typeof import(...).handlers>`. When `false`, `Data`
 *   defaults to `never` (matching the auto-GET runtime fallback).
 */
export function typeFileContent(
  params: readonly string[],
  routePath: string,
  closestMiddleware: string | null,
  userExportsHandlers: boolean,
): string {
  const paramsBody =
    params.length === 0 ? "{}" : `{\n${params.map((p) => `  ${p}: string;`).join("\n")}\n}`;

  const lines: string[] = [
    `// Auto-generated by Fresh — do not edit.`,
    `import type { VNode } from "preact";`,
    `import type { Handler, InferData, PageProps } from "fresh/types";`,
  ];

  if (closestMiddleware) {
    const spec = relativeImport(typeFilePath(routePath), typeFilePath(closestMiddleware));
    lines.push(`import type { State } from ${JSON.stringify(spec)};`);
  } else {
    // Empty interface (not `Record<string, never>`) so the handler's `ctx.state`
    // can still be augmented downstream without TS rejecting added properties.
    lines.push(`interface State {}`);
  }

  if (userExportsHandlers) {
    const sourceBasename = routePath.split("/").pop()!;
    const importSpec = JSON.stringify(`./${sourceBasename}`);
    lines.push(`type Data = InferData<typeof import(${importSpec}).handlers>;`);
  } else {
    lines.push(`type Data = never;`);
  }

  lines.push(
    ``,
    `export interface Params ${paramsBody}`,
    ``,
    `export function handler<H extends Handler<Params, State>>(h: H): H {`,
    `  return h;`,
    `}`,
    ``,
    `// \`page\` is a sibling of \`handler\` (not wrapped in an object) so the`,
    `// page's typing can reference \`InferData<typeof import("./...").handlers>\``,
    `// without TS hitting a circular dependency between the type of a property`,
    `// and the value of \`handlers\` (which references the same object).`,
    `export function page(`,
    `  fn: (props: PageProps<Data, Params, State>) => VNode,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

/**
 * Path + content for a route's typings file.
 */
export function generateRouteTypeFile(
  relativeRoutePath: string,
  params: readonly string[],
  closestMiddleware: string | null,
  userExportsHandlers: boolean,
): GeneratedTypeFile {
  return {
    path: typeFilePath(relativeRoutePath),
    content: typeFileContent(params, relativeRoutePath, closestMiddleware, userExportsHandlers),
  };
}

/**
 * Cheap regex check for `export const handlers` / `export let handlers` /
 * `export function handlers` / `export var handlers` in a route source.
 * Used so the typings file can conditionally emit the `InferData` import.
 */
export function detectHandlersExport(source: string): boolean {
  return /(^|\n)\s*export\s+(?:const|let|var|function)\s+handlers\b/.test(source);
}

/**
 * Render the typings file body for a middleware.
 *
 * `parentMiddleware` is the project-relative path to the parent middleware
 * source (or `null` for the root middleware). `userExportsState` should be
 * `true` when the user's source has `export interface State` or
 * `export type State` — when `false`, `OwnState` falls back to `ParentState`.
 */
export function middlewareTypeFileContent(
  middlewarePath: string,
  parentMiddleware: string | null,
  userExportsState: boolean,
): string {
  const lines: string[] = [
    `// Auto-generated by Fresh — do not edit.`,
    `import type { MiddlewareFn } from "fresh/types";`,
  ];

  if (parentMiddleware) {
    const spec = relativeImport(typeFilePath(middlewarePath), typeFilePath(parentMiddleware));
    lines.push(`import type { State as ParentState } from ${JSON.stringify(spec)};`);
  } else {
    // Empty interface so user code can `interface State extends ParentState {}`
    // and add new properties without bumping into a `Record<string, never>`
    // index signature.
    lines.push(`interface ParentState {}`);
  }

  if (userExportsState) {
    // Direct dotted access into the module type — works for type-only exports
    // (interface/type aliases). The source-scan in writeTypeFiles ensures we
    // only emit this when the user actually exports State.
    const fileName = middlewarePath.split("/").pop()!;
    const importSpec = JSON.stringify(`./${fileName}`);
    lines.push(`type OwnState = import(${importSpec}).State;`);
  } else {
    lines.push(`type OwnState = ParentState;`);
  }

  lines.push(
    ``,
    `export type { ParentState };`,
    `export type State = OwnState;`,
    ``,
    `export function middleware(`,
    `  fn: MiddlewareFn<ParentState, OwnState>,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

/**
 * Render the typings file body for `routes/_app.tsx`.
 *
 * Exports an identity `app` helper typed against `AppProps` (children +
 * `req` access in the user's wrapper component). The wildcard import in the
 * generated route module pulls the default export, so this only needs to
 * surface the `app(...)` helper for ergonomic typing.
 */
export function appTypeFileContent(): string {
  return [
    `// Auto-generated by Fresh — do not edit.`,
    `import type { AppComponent } from "fresh/types";`,
    ``,
    `export function app(fn: AppComponent): AppComponent {`,
    `  return fn;`,
    `}`,
    ``,
  ].join("\n");
}

export function generateAppTypeFile(appPath: string): GeneratedTypeFile {
  return {
    path: typeFilePath(appPath),
    content: appTypeFileContent(),
  };
}

/**
 * Render the typings file body for `routes/.../_layout.tsx`.
 *
 * Exports an identity `layout` helper typed against
 * `LayoutComponent<unknown, Params, State>` — `State` is pulled from the
 * closest `_middleware` (so layouts can read whatever the upstream middleware
 * chain produced), and `Params` defaults to a string-keyed record because
 * layouts apply to multiple sibling routes whose param sets may differ.
 */
export function layoutTypeFileContent(
  layoutPath: string,
  closestMiddleware: string | null,
): string {
  const lines: string[] = [
    `// Auto-generated by Fresh — do not edit.`,
    `import type { LayoutComponent } from "fresh/types";`,
  ];
  if (closestMiddleware) {
    const spec = relativeImport(typeFilePath(layoutPath), typeFilePath(closestMiddleware));
    lines.push(`import type { State } from ${JSON.stringify(spec)};`);
  } else {
    lines.push(`interface State {}`);
  }
  lines.push(
    ``,
    `export function layout(`,
    `  fn: LayoutComponent<unknown, Record<string, string>, State>,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

export function generateLayoutTypeFile(
  layoutPath: string,
  closestMiddleware: string | null,
): GeneratedTypeFile {
  return {
    path: typeFilePath(layoutPath),
    content: layoutTypeFileContent(layoutPath, closestMiddleware),
  };
}

/**
 * Render the typings file body for `routes/_error.tsx`.
 *
 * `State` is the union of every middleware's `State` plus `EmptyState` — the
 * error route is reachable from any route (including a 404 with no
 * middleware chain), so any one of these states might be the live one at
 * dispatch time.
 *
 * Emits both a typed `handler` helper (whose context carries `error`) and a
 * typed `page` helper (whose props carry `error`).
 */
export function errorTypeFileContent(errorPath: string, allMiddlewares: readonly string[]): string {
  const lines: string[] = [
    `// Auto-generated by Fresh — do not edit.`,
    `import type { VNode } from "preact";`,
    `import type { EmptyState, ErrorHandler, ErrorPageProps, InferData } from "fresh/types";`,
  ];

  // Pull each middleware's State as a distinct alias, then union them.
  const aliases: string[] = ["EmptyState"];
  allMiddlewares.forEach((mw, i) => {
    const spec = relativeImport(typeFilePath(errorPath), typeFilePath(mw));
    const alias = `State_${i}`;
    lines.push(`import type { State as ${alias} } from ${JSON.stringify(spec)};`);
    aliases.push(alias);
  });

  lines.push(``, `type State = ${aliases.join(" | ")};`);

  // `_error.tsx` carries no URL params (it's not URL-addressable).
  lines.push(`export interface Params {}`);

  // Data is inferred from `handlers` (same approach as a normal route).
  const sourceBasename = errorPath.split("/").pop()!;
  const importSpec = JSON.stringify(`./${sourceBasename}`);
  lines.push(`type Data = InferData<typeof import(${importSpec}).handlers>;`);

  lines.push(
    ``,
    `export function handler<H extends ErrorHandler<Params, State>>(h: H): H {`,
    `  return h;`,
    `}`,
    ``,
    `export function page(`,
    `  fn: (props: ErrorPageProps<Data, Params, State>) => VNode,`,
    `): typeof fn {`,
    `  return fn;`,
    `}`,
    ``,
  );
  return lines.join("\n");
}

export function generateErrorTypeFile(
  errorPath: string,
  allMiddlewares: readonly string[],
): GeneratedTypeFile {
  return {
    path: typeFilePath(errorPath),
    content: errorTypeFileContent(errorPath, allMiddlewares),
  };
}

export function generateMiddlewareTypeFile(
  middlewarePath: string,
  parentMiddleware: string | null,
  userExportsState: boolean,
): GeneratedTypeFile {
  return {
    path: typeFilePath(middlewarePath),
    content: middlewareTypeFileContent(middlewarePath, parentMiddleware, userExportsState),
  };
}

/**
 * Cheap regex check for `export interface State` / `export type State` in a
 * middleware source. Avoids pulling in a TS parser for a one-liner test;
 * good enough for what middleware files look like in practice.
 */
export function detectStateExport(source: string): boolean {
  return /(^|\n)\s*export\s+(?:interface|type)\s+State\b/.test(source);
}

/**
 * Extract dynamic param names from a route source file path. Works on both
 * the `[name]` and `[...name]` (catch-all) forms.
 */
export function paramsFromFilePath(filePath: string): string[] {
  const out: string[] = [];
  const re = /\[(?:\.{3})?([^\]]+)\]/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(filePath)) !== null) {
    out.push(m[1]);
  }
  return out;
}

/** POSIX-style relative import specifier from one typings file to another. */
function relativeImport(fromPath: string, toPath: string): string {
  const fromDir = fromPath.split("/").slice(0, -1);
  const toParts = toPath.split("/");
  // Walk common prefix.
  let i = 0;
  while (i < fromDir.length && i < toParts.length - 1 && fromDir[i] === toParts[i]) {
    i++;
  }
  const ups = fromDir.length - i;
  const segs = toParts.slice(i);
  const rel = (ups === 0 ? ["."] : Array(ups).fill("..")).concat(segs).join("/");
  // Strip the `.ts` so the import works under TS's standard module resolution.
  return rel.replace(/\.ts$/, "");
}
